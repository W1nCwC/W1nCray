#!/usr/bin/env bash
# make-panel-manifest.sh — regenerate panel-files.txt from the panel checkout.
#
# panel-files.txt is the exact list of files 10-panel-files.sh copies into
# /www/wwwroot/xboard.  It is committed so the deployment is auditable: you can
# diff the list instead of trusting a glob.
#
# The list is a superset of "what changed": every file that belongs to the
# W1nCray control plane is listed whether or not it changed since the baseline.
# Re-copying an unchanged file is harmless (it is backed up first); missing a
# changed one is a fatal `require` error inside the panel.
#
# The scope is explicit, not "the whole directory": app/Models has hundreds of
# unrelated models and app/Console/Commands has two dozen unrelated commands,
# and copying them would widen the backup for no reason.
#
# Files DELETED by this release (the legacy UniProxy controllers, middleware and
# routes) are deliberately NOT in the list.  Removing them is a separate,
# opt-in decision — see docs/DEPLOY-v9.md §7.
#
# Usage:
#   scripts/deploy-v9/make-panel-manifest.sh [--src <dir>] [--out <file>]
#   scripts/deploy-v9/make-panel-manifest.sh --report   # show what changed vs 128ec1f
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
. "$HERE/lib.sh"
require_strict_mode

BASE="128ec1f"                       # sub12: the last panel state in production
SRC="${PANEL_SRC:-C:/W1nCBoard}"
OUT="$HERE/panel-files.txt"
REPORT=0

while [ $# -gt 0 ]; do
  case "$1" in
    --base)   BASE="$2"; shift ;;
    --src)    SRC="$2";  shift ;;
    --out)    OUT="$2";  shift ;;
    --report) REPORT=1 ;;
    -h|--help) log "usage: $0 [--base <commit>] [--src <panel checkout>] [--out <file>] [--report]"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
  shift
done

[ -d "$SRC/.git" ] || die "not a git checkout: $SRC"
git -C "$SRC" rev-parse --verify "$BASE" >/dev/null 2>&1 || die "unknown baseline commit: $BASE"

if [ "$REPORT" = "1" ]; then
  log "changed since $BASE (deletions marked with '!', they are NOT deployed):"
  git -C "$SRC" diff --name-status "$BASE" HEAD | sed -e 's/^D/!/' | sort -k2
  exit 0
fi

log "panel checkout : $SRC"
log "baseline       : $BASE  ($(git -C "$SRC" log -1 --pretty=%s "$BASE"))"
log "head           : $(git -C "$SRC" rev-parse --short HEAD)  ($(git -C "$SRC" log -1 --pretty=%s HEAD))"
log "output         : $OUT"
log ""

# ---------------------------------------------------------------------------
# The scope.  Directories are expanded (files only); single files are added
# as-is.  A missing entry aborts: a silent omission is the one failure mode
# that reaches production.
# ---------------------------------------------------------------------------
SCOPE_DIRS=(
  app/Http/Controllers/V2/Admin/W1nCray
  app/Http/Controllers/V2/Agent
  app/Services/Agent
  app/WebSocket
  database/migrations
  public/w1ncray
  resources/views/w1ncray
)
SCOPE_FILES=(
  app/Console/Commands/AgentInstanceCommand.php
  app/Console/Commands/AgentManifestCommand.php
  app/Console/Commands/CleanupOnlineStatus.php
  app/Console/Commands/PruneAgentSamples.php
  app/Console/Commands/W1nCrayWebSocketServer.php
  app/Console/Kernel.php
  app/Http/Controllers/V2/Admin/Server/MachineController.php
  app/Http/Kernel.php
  app/Http/Middleware/AgentNodeScope.php
  app/Http/Middleware/W1nCrayRequestLog.php
  app/Http/Routes/V2/AdminRoute.php
  app/Http/Routes/V2/AgentFileRoute.php
  app/Http/Routes/V2/AgentManifestRoute.php
  app/Http/Routes/V2/AgentNodeRoute.php
  app/Http/Routes/V2/AgentRoute.php
  app/Http/Routes/V2/W1nCrayAdminRoute.php
  app/Http/Routes/V2/W1nCrayFileAdminRoute.php
  app/Http/Routes/V2/W1nCrayKernelAdminRoute.php
  app/Http/Routes/V2/W1nCrayManifestAdminRoute.php
  app/Http/Routes/V2/W1nCrayMonitorAdminRoute.php
  app/Http/Routes/V2/W1nCrayPageRoute.php
  app/Http/Routes/V2/W1nCrayTerminalAdminRoute.php
  app/Http/Routes/V2/W1nCrayWsAdminRoute.php
  app/Models/AgentAudit.php
  app/Models/AgentCommand.php
  app/Models/AgentFile.php
  app/Models/AgentFileBlob.php
  app/Models/AgentFileVersion.php
  app/Models/AgentHostSample.php
  app/Models/AgentInstance.php
  app/Models/AgentInstanceStatus.php
  app/Models/AgentMachineState.php
  app/Models/AgentRevision.php
  app/Models/AgentTerminalSession.php
  app/Models/ServerMachine.php
  app/Models/ServerMachineLoadHistory.php
  app/Services/DeviceStateService.php
  app/Services/ServerService.php
  config/w1ncray.php
  storage/app/w1ncray/.gitignore
)

MISSING=0
{
  echo "# panel-files.txt — files 10-panel-files.sh copies into /www/wwwroot/xboard"
  echo "# generated by scripts/deploy-v9/make-panel-manifest.sh"
  echo "# baseline: $BASE (last panel state in production, the sub12 redirect)"
  echo "# head:     $(git -C "$SRC" rev-parse --short HEAD)"
  echo "# one relative path per line; '#' comments and blank lines are ignored"
  echo "#"
  echo "# whole directories:"
  for d in "${SCOPE_DIRS[@]}"; do echo "#   $d"; done
  echo "# single files:      ${#SCOPE_FILES[@]} entries"
  echo "#"
  for d in "${SCOPE_DIRS[@]}"; do
    if [ ! -d "$SRC/$d" ]; then
      echo "# MISSING-DIR $d" >&2
      MISSING=$((MISSING + 1))
      continue
    fi
    find "$SRC/$d" -type f -printf '%P\n' | sed "s|^|$d/|"
  done
  for f in "${SCOPE_FILES[@]}"; do
    if [ ! -f "$SRC/$f" ]; then
      echo "# MISSING-FILE $f" >&2
      MISSING=$((MISSING + 1))
      continue
    fi
    printf '%s\n' "$f"
  done
} | sort -u > "$OUT"

[ "$MISSING" -eq 0 ] || die "$MISSING scope entr(ies) missing in $SRC — fix the scope before deploying"

# `find -printf` is GNU-specific; Git for Windows and Linux both have it.  If it
# were missing the file would be almost empty — fail loudly instead of deploying
# a truncated manifest.
N=$(grep -v -E '^[[:space:]]*(#|$)' "$OUT" | wc -l | tr -d ' ')
[ "$N" -ge 150 ] || die "only $N entries — 'find -printf' probably failed; refusing to write a truncated manifest"

log "wrote $N entries"
log ""
check_manifest_local "$SRC" "$OUT"

# ---------------------------------------------------------------------------
# Cross-check: every file this release CHANGED (except the deliberate
# deletions) must be in the list.  This is the check that catches a forgotten
# scope entry.
# ---------------------------------------------------------------------------
log ""
log "cross-check against 'git diff --name-only $BASE HEAD':"
GAPS=0
while IFS=$'\t' read -r st f; do
  [ -n "$f" ] || continue
  case "$st" in D*) continue ;; esac
  case "$f" in
    tests/*|docs/*|frontend-overlay/*) continue ;;
  esac
  if grep -qxF "$f" <(grep -v -E '^[[:space:]]*(#|$)' "$OUT"); then
    printf '  ok       %s\n' "$f"
  else
    printf '  GAP      %s\n' "$f"
    GAPS=$((GAPS + 1))
  fi
done < <(git -C "$SRC" diff --name-status "$BASE" HEAD)

if [ "$GAPS" -gt 0 ]; then
  fail "$GAPS changed file(s) are not in the manifest — add them to SCOPE_DIRS/SCOPE_FILES"
  exit 1
fi
ok "manifest covers every changed file; deletions are left to docs/DEPLOY-v9.md §7"
